with agg as (
	select
		edition_id,
		competition_id,
		competition_phase,
		team_id,
		any_value(team_name) as team_name,
		any_value(club_id) as club_id,
		any_value(club_name) as club_name,
		count(1) as games,
		count(*) filter (where has_possessions) as games_with_possessions,
		sum(case when points > opponent_points then 1 else 0 end) as wins,
		sum(case when points < opponent_points then 1 else 0 end) as losses,
		sum(seconds) as seconds,
		sum(points) as points,
		sum(opponent_points) as opponent_points,
		sum(free_throws_made) as free_throws_made,
		sum(free_throws_attempted) as free_throws_attempted,
		sum(two_pointers_made) as two_pointers_made,
		sum(two_pointers_attempted) as two_pointers_attempted,
		sum(three_pointers_made) as three_pointers_made,
		sum(three_pointers_attempted) as three_pointers_attempted,
		sum(field_goals_made) as field_goals_made,
		sum(field_goals_attempted) as field_goals_attempted,
		sum(dunks) as dunks,
		sum(assists) as assists,
		sum(off_rebounds) as off_rebounds,
		sum(def_rebounds) as def_rebounds,
		sum(total_rebounds) as total_rebounds,
		sum(steals) as steals,
		sum(turnovers) as turnovers,
		sum(blocks) as blocks,
		sum(received_blocks) as received_blocks,
		sum(personal_fouls) as personal_fouls,
		sum(fouls_drawn) as fouls_drawn,
		sum(rating) as rating,
        sum(offensive_possessions) as offensive_possessions,
        sum(defensive_possessions) as defensive_possessions,
        sum(possessions) as possessions,
        -- puntos de los partidos que tienen posesiones: en temporadas con play-by-play incompleto
        -- dividir todos los puntos entre las posesiones de solo algunos partidos inflaba los ratings
        sum(points) filter (where has_possessions) as possession_points,
        sum(opponent_points) filter (where has_possessions) as possession_opponent_points
	from {{ ref('fact_team_games') }}
	group by edition_id, competition_id, competition_phase, team_id
)
select 
	edition_id,
    competition_id,
    competition_phase,
    team_id,
    team_name,
    club_id,
    club_name,
	games,
	games_with_possessions,
	wins,
	losses,
    seconds,
	points,
	opponent_points,
	free_throws_made,
	free_throws_attempted,
	free_throws_made / NULLIF(free_throws_attempted, 0) AS free_throws_pct,
	two_pointers_made,
	two_pointers_attempted,
	two_pointers_made / NULLIF(two_pointers_attempted, 0) AS two_pointers_pct,
	three_pointers_made,
	three_pointers_attempted,
	three_pointers_made / NULLIF(three_pointers_attempted, 0) AS three_pointers_pct,
	field_goals_made,
	field_goals_attempted,
	(two_pointers_made + three_pointers_made) / NULLIF(two_pointers_attempted + three_pointers_attempted, 0) AS field_goals_pct,
	(two_pointers_made + 1.5 * three_pointers_made) / NULLIF(two_pointers_attempted + three_pointers_attempted, 0) AS effective_field_goals_pct,
	points / NULLIF(2 * (two_pointers_attempted + three_pointers_attempted + 0.44 * free_throws_attempted), 0) AS true_shooting_pct,
	dunks,
	assists,
	off_rebounds,
	def_rebounds,
	total_rebounds,
	steals,
	turnovers,
	blocks,
	received_blocks,
	personal_fouls,
	fouls_drawn,
	rating,
	offensive_possessions,
	defensive_possessions,
    possessions,
    possession_points,
    possession_opponent_points,
    100.0 * possession_points / NULLIF(offensive_possessions, 0) as offensive_rating,
    100.0 * possession_opponent_points / NULLIF(defensive_possessions, 0) as defensive_rating,
    100.0 * (possession_points / NULLIF(offensive_possessions, 0) - possession_opponent_points / NULLIF(defensive_possessions, 0)) as net_rating
from agg